-- Task Management Planner database schema
-- Run this file in your Supabase project's SQL Editor.

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title varchar(120) not null check (char_length(trim(title)) between 1 and 120),
  description varchar(1000) not null default '',
  due_date date not null,
  priority varchar(10) not null default 'Medium'
    check (priority in ('Low', 'Medium', 'High')),
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tasks_due_date_idx on public.tasks (due_date);
create index if not exists tasks_completed_idx on public.tasks (completed);
create index if not exists tasks_priority_idx on public.tasks (priority);

create or replace function public.set_task_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists tasks_set_updated_at on public.tasks;
create trigger tasks_set_updated_at
before update on public.tasks
for each row execute function public.set_task_updated_at();

-- This student MVP accesses Supabase through a server-only secret key.
-- Do not expose that key to the browser. Restrict access to this project and
-- never deploy this unrestricted demo API publicly without adding authentication.
alter table public.tasks enable row level security;

